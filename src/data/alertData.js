/**
 * Derives structured, accountable alert records from Phase 13 Risk Events
 * and attaches intervention workflow state.
 */
export const deriveAlertsFromRiskEvents = (
  projectId = 'proj-1',
  riskEvents = [],
  scheduleData = {},
  executionData = {},
  siteViewData = {},
  evidenceData = {}
) => {
  const safeEvents = Array.isArray(riskEvents) ? riskEvents : [];
  const zones = siteViewData?.zones || [];
  const capturePoints = siteViewData?.capturePoints || [];
  const evidenceList = evidenceData?.evidence || [];

  return safeEvents.map((risk, index) => {
    // Generate clean stable alert ID
    const alertNumber = String(index + 1).padStart(4, '0');
    const id = `ALT-${alertNumber}`;

    // Map severity and alert type
    const alertType = risk.riskType || risk.category || 'scheduleVariance';
    const severity = risk.severity || 'high';

    // Derive realistic initial workflow state for rich prototype demonstration
    let status = 'new';
    let escalationLevel = 'normal';
    let assignedTo = 'R. Sharma (Site Engineer)';
    let acknowledgedAt = null;
    let acknowledgedBy = null;
    let actionStartedAt = null;
    let resolvedAt = null;
    let resolutionNote = '';

    if (index === 0) {
      status = 'new';
      escalationLevel = severity === 'critical' ? 'critical' : 'escalated';
      assignedTo = 'V. Menon (Project Manager)';
    } else if (index === 1) {
      status = 'actionInProgress';
      escalationLevel = 'normal';
      assignedTo = 'S. Patel (Senior Resident Engineer)';
      acknowledgedAt = '2026-03-27T09:15:00Z';
      acknowledgedBy = 'S. Patel';
      actionStartedAt = '2026-03-27T11:30:00Z';
    } else if (index === 2) {
      status = 'acknowledged';
      escalationLevel = 'normal';
      assignedTo = 'M. Gupta (Contractor Lead)';
      acknowledgedAt = '2026-03-28T08:45:00Z';
      acknowledgedBy = 'M. Gupta';
    } else if (index === safeEvents.length - 1 && safeEvents.length > 3) {
      status = 'resolved';
      escalationLevel = 'normal';
      assignedTo = 'A. Kumar (QA Inspector)';
      acknowledgedAt = '2026-03-25T14:00:00Z';
      acknowledgedBy = 'A. Kumar';
      actionStartedAt = '2026-03-25T15:30:00Z';
      resolvedAt = '2026-03-26T18:00:00Z';
      resolutionNote = 'Intermediate cube test reports verified (38.5 MPa achieved). QA certificate signed off.';
    }

    // Resolve Spatial Context
    const scope = risk.impactedScope || {};
    const matchingZone = zones.find((z) => {
      if (scope.zoneId && z.id === scope.zoneId) return true;
      if (scope.wbsId && (z.wbsIds || []).includes(scope.wbsId)) return true;
      if (scope.phaseId && z.phaseId === scope.phaseId) return true;
      return false;
    });

    const matchingCapturePoints = matchingZone
      ? capturePoints.filter((cp) => cp.zoneId === matchingZone.id)
      : [];

    // Resolve Linked Evidence
    const linkedEvidence = evidenceList.filter((ev) => {
      if (Array.isArray(risk.evidenceIds) && risk.evidenceIds.includes(ev.id)) return true;
      if (scope.microActivityId && ev.microActivityId === scope.microActivityId) return true;
      if (scope.activityId && ev.activityId === scope.activityId) return true;
      return false;
    });

    // Derive Schedule Impact statement
    const observed = risk.observedValues || {};
    const variance = observed.variance || risk.indicators?.variance || 0;
    let scheduleImpact = 'Execution variance may propagate to immediate downstream predecessor activities.';
    if (observed.criticalPath || risk.indicators?.criticalPath) {
      scheduleImpact = `Critical-path variance (${variance} pp) directly erodes total project buffer and milestone target date.`;
    } else if (variance <= -10) {
      scheduleImpact = `Significant physical delay (${Math.abs(variance)} pp gap) requires workfront acceleration to preserve window.`;
    } else if (alertType === 'executionBlockage') {
      scheduleImpact = 'Active workfront stoppage preventing physical progress until interface constraint is cleared.';
    } else if (alertType === 'qaPending') {
      scheduleImpact = 'Successor pour/erection stage cannot commence until formal inspection certification is recorded.';
    }

    // Workflow History Audit Trail
    const workflowHistory = [
      {
        id: `hist-${id}-1`,
        type: 'detected',
        title: 'Alert Triggered',
        timestamp: risk.detectedAt || '2026-03-28T14:30:00Z',
        actor: `Rule Engine (${risk.triggerRule || 'RULE_EVALUATOR'})`,
        note: risk.explanation || 'Execution variance threshold condition observed.',
      },
    ];

    if (acknowledgedAt) {
      workflowHistory.push({
        id: `hist-${id}-2`,
        type: 'acknowledged',
        title: 'Alert Acknowledged',
        timestamp: acknowledgedAt,
        actor: acknowledgedBy || assignedTo,
        note: 'Responsible engineer acknowledged execution condition.',
      });
    }

    if (actionStartedAt) {
      workflowHistory.push({
        id: `hist-${id}-3`,
        type: 'actionInProgress',
        title: 'Action Started',
        timestamp: actionStartedAt,
        actor: assignedTo,
        note: 'Mitigation measures initiated at the workfront.',
      });
    }

    if (escalationLevel !== 'normal') {
      workflowHistory.push({
        id: `hist-${id}-4`,
        type: 'escalated',
        title: `Escalated to ${escalationLevel === 'critical' ? 'Project Authority' : 'Project Manager'}`,
        timestamp: '2026-03-28T15:00:00Z',
        actor: 'Intervention Matrix',
        note: 'Threshold duration exceeded without resolution; escalation dispatched.',
      });
    }

    if (resolvedAt) {
      workflowHistory.push({
        id: `hist-${id}-5`,
        type: 'resolved',
        title: 'Alert Resolved',
        timestamp: resolvedAt,
        actor: assignedTo,
        note: resolutionNote || 'Condition resolved and verified.',
      });
    }

    return {
      id,
      projectId,
      riskEventId: risk.id,
      alertType,
      severity,
      status,
      title: risk.title || 'Execution Threshold Alert',
      summary: risk.explanation || 'Project execution condition requiring human intervention.',
      detectedAt: risk.detectedAt || '2026-03-28T14:30:00Z',
      impactedScope: {
        phaseId: scope.phaseId || 'PH-01',
        phaseName: scope.phaseName || 'Substructure & Foundations',
        wbsId: scope.wbsId || 'WBS-01-01',
        wbsName: scope.wbsName || 'Foundation Package',
        activityId: scope.activityId || 'ACT-01',
        activityName: scope.activityName || 'Civil Construction',
        microActivityId: scope.microActivityId || null,
        microActivityName: scope.microActivityName || null,
        zoneId: matchingZone?.id || null,
        zoneCode: matchingZone?.code || null,
        zoneName: matchingZone?.name || null,
      },
      projectArea: matchingZone ? `${matchingZone.code} (${matchingZone.name})` : 'Project Corridor',
      discipline: risk.discipline || { id: 'disc-civil', name: 'Civil & Structural' },
      contractor: risk.contractor || { id: 'cont-1', name: 'Apex Engineering Ltd.' },
      triggerCondition: risk.explanation || 'Rule condition observed',
      scheduleImpact,
      evidenceContext: {
        linkedEvidenceIds: linkedEvidence.map((e) => e.id),
        evidenceCount: linkedEvidence.length,
        evidenceRecords: linkedEvidence,
        status: linkedEvidence.length > 0 ? 'available' : 'gap',
      },
      spatialContext: matchingZone
        ? {
            zoneId: matchingZone.id,
            zoneCode: matchingZone.code,
            zoneName: matchingZone.name,
            stationing: matchingZone.name.match(/CH\s+[\d+.]+(\s*-\s*CH\s+[\d+.]+)?/i)?.[0] || 'CH 0+000',
            latitude: (30.7046 + index * 0.003).toFixed(4),
            longitude: (76.7179 + index * 0.004).toFixed(4),
            capturePoints: matchingCapturePoints,
          }
        : null,
      recommendedAction:
        risk.recommendedAction?.action ||
        'Review workfront constraints and coordinate recovery schedule with responsible engineer.',
      responsibleRole:
        risk.recommendedAction?.responsibleRole || 'Project Manager / Site Engineer',
      assignedTo,
      acknowledgedAt,
      acknowledgedBy,
      actionStartedAt,
      resolvedAt,
      resolutionNote,
      escalationLevel,
      workflowHistory,
      sourceReferences: {
        scheduleRef: `${scheduleData?.meta?.baselineRef || 'Primavera P6 Baseline'} (${scope.activityId || 'ACT'})`,
        executionRef: `Execution Record ${scope.microActivityId || scope.activityId || 'Unit'}`,
        siteViewRef: matchingZone ? `${matchingZone.code} — ${matchingZone.name}` : 'Site Registry',
        evidenceRef: linkedEvidence.length > 0 ? linkedEvidence.map((e) => e.id).join(', ') : 'None',
      },
    };
  });
};

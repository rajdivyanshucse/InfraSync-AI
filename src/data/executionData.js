/**
 * Helper to fetch execution dataset by project ID
 */
export const getExecutionData = (projectId) => {
  return projectExecutionData[projectId] || projectExecutionData['proj-1'];
};

/**
 * Helper to fetch micro-activities for a specific schedule activity
 */
export const getMicroActivitiesForActivity = (projectId, activityId) => {
  const data = getExecutionData(projectId);
  return (data.microActivities || []).filter((m) => m.activityId === activityId);
};

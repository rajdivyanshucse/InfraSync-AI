import mongoose from 'mongoose';
import { config } from '../config/env.js';
import { RiskEvent } from '../models/RiskEvent.js';
import { risksData } from '../data/risks.data.js';

export class RiskRepository {
  async getRiskEventsByProjectId(projectId) {
    if (config.dataSource === 'mongodb' && mongoose.connection.readyState === 1) {
      const docs = await RiskEvent.find({ projectId }).lean();
      return docs.map(this._cleanDoc);
    }
    return risksData[projectId] || [];
  }

  async getRiskEventById(projectId, riskId) {
    if (config.dataSource === 'mongodb' && mongoose.connection.readyState === 1) {
      const doc = await RiskEvent.findOne({ projectId, id: riskId }).lean();
      return doc ? this._cleanDoc(doc) : null;
    }
    const list = risksData[projectId] || [];
    return list.find((r) => r.id === riskId) || null;
  }

  async updateAcknowledgement(projectId, riskId, acknowledged, actor = null) {
    const timestamp = new Date().toISOString();
    const updatePayload = {
      acknowledged: Boolean(acknowledged),
      acknowledgedBy: acknowledged ? (actor?.name || actor?.userId || 'Authorized User') : null,
      acknowledgedAt: acknowledged ? timestamp : null,
    };

    if (config.dataSource === 'mongodb' && mongoose.connection.readyState === 1) {
      const doc = await RiskEvent.findOneAndUpdate(
        { projectId, id: riskId },
        { $set: updatePayload },
        { new: true, runValidators: true }
      ).lean();
      return doc ? this._cleanDoc(doc) : null;
    }

    if (!risksData[projectId]) {
      risksData[projectId] = [];
    }
    const list = risksData[projectId];
    const index = list.findIndex((r) => r.id === riskId);
    if (index !== -1) {
      list[index] = {
        ...list[index],
        ...updatePayload,
      };
      return list[index];
    }

    // If event was dynamically generated by calculation engine, seed it into the store
    const newEvent = {
      id: riskId,
      projectId,
      title: `Risk Event ${riskId}`,
      severity: 'medium',
      riskType: 'scheduleFloatErosion',
      ...updatePayload,
    };
    list.push(newEvent);
    return newEvent;
  }

  _cleanDoc(doc) {
    if (!doc) return null;
    const { _id, __v, ...rest } = doc;
    return rest;
  }
}

export const riskRepository = new RiskRepository();
